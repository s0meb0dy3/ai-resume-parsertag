def build_positive_value_guidance(
    dimension: str,
    allowed_values: list[str],
    skill_records: list[dict] | None = None,
) -> str:
    """按运行时允许值生成逐值判定说明。

    Args:
        dimension: 正向标签维度标识。
        allowed_values: 当前运行时配置允许输出的标准值。
        skill_records: 技能维度的标准值、分类和唯一别名记录。

    Returns:
        每个允许值一条、带序号的 Prompt 文本。技能候选为空时返回严格空数组
        约束；其他维度允许值为空时返回自由提取说明。

    Note:
        固定维度出现未维护的新值时使用严格默认规则，确保配置变更后每个值仍有
        独立说明，但不会凭名称猜测宽泛语义。
    """
    if dimension == "skills" and not allowed_values:
        return (
            "1. 当前简历未召回任何有直接证据的标准技能候选，必须返回 "
            "`skillsValueArray=[]`；不得从岗位要求、常识或技能库自由补充。"
        )
    if not allowed_values:
        return "1. `allowedValues` 为空：仅提取有直接证据且与维度名称严格一致的值。"

    skill_by_value = {
        str(record.get("value", "")): record
        for record in (skill_records or [])
    }
    authored_guidance = VALUE_GUIDANCE_BY_DIMENSION.get(dimension, {})
    lines: list[str] = []
    for index, value in enumerate(allowed_values, start=1):
        if dimension == "skills" and value in skill_by_value:
            record = skill_by_value[value]
            aliases = "、".join(record.get("aliases", [])) or "无"
            category = record.get("category", "未分类")
            special_boundary = SKILL_VALUE_GUIDANCE_OVERRIDES.get(value, "")
            guidance = (
                f"分类为“{category}”，可识别唯一别名：{aliases}。只有职责、项目、"
                "技能清单或自我评价明确表明候选人实际使用、掌握或负责该技能时"
                "才输出；岗位要求、客户技术、待学习、否定表述和宽泛近义词不输出。"
            )
            if special_boundary:
                guidance = f"{guidance}{special_boundary}"
        else:
            guidance = authored_guidance.get(
                value,
                "仅当简历存在可复核且直接对应本标准值的证据时输出；"
                "名称相似、信息缺失、岗位要求或无关上下文不作为命中依据。",
            )
        lines.append(f"{index}. `{value}`：{guidance} 标准输出必须原样使用 `{value}`。")
    return "\n".join(lines)
